import { expect, test } from 'vitest'
import { asOfLabel, greetingDate } from './home-time'

// 끼룩이 한 줄의 기준 시각(DEC-95): 서버가 응답을 만든 시각을 한국 시간으로 읽고, 홈의 오늘과 같은 날이면 시각만 쓴다.
test('기준 시각이 오늘이면 시각만 쓴다', () => {
  expect(asOfLabel('2026-10-26T05:05:00.000Z', '2026-10-26')).toBe('14:05')
})

test('기준 시각이 다른 날이면 날짜와 요일을 붙인다', () => {
  expect(asOfLabel('2026-10-25T05:05:00.000Z', '2026-10-26')).toBe('10월 25일 (일) 14:05')
})

test('날짜는 UTC가 아니라 한국 날짜로 가른다', () => {
  // UTC로는 25일이지만 한국 시간으로는 26일 00:30이다.
  expect(asOfLabel('2026-10-25T15:30:00.000Z', '2026-10-26')).toBe('00:30')
  // UTC로는 26일이지만 한국 시간으로는 27일이라 오늘(26일)과 다르다.
  expect(asOfLabel('2026-10-26T15:00:00.000Z', '2026-10-26')).toBe('10월 27일 (화) 00:00')
})

test('올해가 아닌 기준 시각에는 해를 붙인다', () => {
  expect(asOfLabel('2025-12-31T05:00:00.000Z', '2026-01-02')).toBe('2025년 12월 31일 (수) 14:00')
})

test('인사 카드의 날짜는 홈의 오늘에 요일을 붙인다', () => {
  expect(greetingDate('2026-10-26')).toBe('10월 26일 (월)')
  expect(greetingDate('2026-10-25')).toBe('10월 25일 (일)')
})
