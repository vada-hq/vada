import { defineConfig } from 'vitest/config'

// **검사는 UTC에서 돈다.**
//
// 서버가 시각을 글로 만드는데, 오랫동안 그 글이 **기계의 시간대**로 찍혔다. 내 기계는
// 한국이라 검사가 통과했고 CI가 UTC로 돌자 네 개가 한꺼번에 깨졌다(2026-09-01) —
// 배포했으면 아무 오류 없이 모든 시각이 아홉 시간 어긋난 채 보였을 것이다.
//
// 이제 `time.ts`가 시간대를 못 박으므로 어디서 돌든 같은 답이 나온다. 그것이 정말
// 그런지 재려면 **한국이 아닌 곳에서 돌려야 한다** — 한국에서 도는 검사는 아무것도
// 증명하지 못한다. 여기서 정하면 내 기계와 CI가 같아진다.
process.env.TZ = 'UTC'

// 검사 파일들이 **한 프로세스에서** 돈다.
//
// 진짜 Postgres(PGlite)를 띄우는 데 7초쯤 걸린다. 파일마다 다른 프로세스면 파일마다
// 띄우게 되고, 지금 셋이라 그것만으로 20초가 넘는다 — 게이트의 시간 예산을 먹는다.
//
// 한 프로세스면 `db/testing.ts`가 띄운 것을 파일들이 나눠 쓴다. 깨끗함은 파일마다
// 표를 지우고 다시 만들어 지킨다(100ms가 안 된다).
export default defineConfig({
  test: {
    // **변환한 것을 다음 실행까지 남긴다.**
    //
    // vitest가 스스로 알려 준 값이다 — "transforming modules took 73.34s · 45% of
    // tracked time, re-done on every run". 검사 파일 하나를 고치고 다시 재는 데
    // 20.8초가 드는데 그중 실제 테스트는 1.6초였다(2026-09-09에 쟀다). 나머지는
    // 매번 처음부터 다시 하는 변환이다.
    //
    // **위험이 있다.** 캐시가 어긋나면 옛 코드에 초록이 뜬다 — 이 저장소에서 가장
    // 나쁜 실패 모드다. 그래서 막는 자리를 함께 둔다: 캐시는 `node_modules/.vite`에
    // 살고 CI는 매번 새 러너에서 `npm ci`로 시작하므로 **원격 게이트는 늘 차갑다.**
    // 내 기계에서만 초록인 것은 거기서 걸린다. 그 사실을 `tests/gate-cold.test.mjs`가
    // 지킨다 — 누가 CI에 캐시를 심으면 그 검사가 터진다.
    fsModuleCache: true,
    pool: 'forks',
    // Vitest 4에서 poolOptions가 없어졌다 — 최상위로 올라왔다. 옛 모양으로 두면
    // **경고만 뜨고 조용히 안 걸린다.**
    isolate: false,
    maxWorkers: 1,
    minWorkers: 1,
  },
})
